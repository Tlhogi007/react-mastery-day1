#!/usr/bin/env node

/**
 * Auto-generate contentLoader.ts from markdown files
 * Reads all files in content/community/ and creates the loader
 */

const fs = require('fs');
const path = require('path');

const CONTENT_DIR = path.join(__dirname, '../content/community');
const OUTPUT_FILE = path.join(__dirname, '../src/lib/contentLoader.ts');

// Parse frontmatter from markdown
function parseFrontmatter(content) {
  const frontmatterRegex = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/;
  const match = content.match(frontmatterRegex);
  
  if (!match) {
    return { metadata: {}, content: content };
  }
  
  const [, frontmatter, body] = match;
  const metadata = {};
  
  frontmatter.split('\n').forEach(line => {
    const [key, ...valueParts] = line.split(':');
    if (key && valueParts.length) {
      let value = valueParts.join(':').trim();
      
      // Remove quotes
      value = value.replace(/^["']|["']$/g, '');
      
      // Parse arrays
      if (value.startsWith('[') && value.endsWith(']')) {
        value = value.slice(1, -1).split(',').map(v => v.trim().replace(/^["']|["']$/g, ''));
      }
      
      metadata[key.trim()] = value;
    }
  });
  
  return { metadata, content: body.trim() };
}

// Get all markdown files recursively
function getMarkdownFiles(dir) {
  const files = [];
  
  if (!fs.existsSync(dir)) {
    console.log(`⚠️  Directory not found: ${dir}`);
    return files;
  }
  
  const items = fs.readdirSync(dir);
  
  items.forEach(item => {
    const fullPath = path.join(dir, item);
    const stat = fs.statSync(fullPath);
    
    if (stat.isDirectory()) {
      files.push(...getMarkdownFiles(fullPath));
    } else if (item.endsWith('.md')) {
      files.push(fullPath);
    }
  });
  
  return files;
}

// Generate slug from filename
function generateSlug(filepath) {
  const filename = path.basename(filepath, '.md');
  return filename.toLowerCase().replace(/[^a-z0-9]+/g, '-');
}

// Main function
function generateContentLoader() {
  console.log('🔄 Generating content loader...\n');
  
  const markdownFiles = getMarkdownFiles(CONTENT_DIR);
  
  if (markdownFiles.length === 0) {
    console.log('📝 No community contributions found yet.');
    console.log('   Content will be generated when contributions are added.\n');
  } else {
    console.log(`📚 Found ${markdownFiles.length} contribution(s):\n`);
  }
  
  const contributions = [];
  
  markdownFiles.forEach(filepath => {
    const content = fs.readFileSync(filepath, 'utf-8');
    const { metadata, content: body } = parseFrontmatter(content);
    const slug = generateSlug(filepath);
    
    console.log(`   ✅ ${metadata.title || slug}`);
    
    contributions.push({
      slug,
      title: metadata.title || 'Untitled',
      author: metadata.author || 'Anonymous',
      github: metadata.github || undefined,
      twitter: metadata.twitter || undefined,
      linkedin: metadata.linkedin || undefined,
      topic: metadata.topic || 'General',
      difficulty: metadata.difficulty || 'intermediate',
      date: metadata.date || new Date().toISOString().split('T')[0],
      tags: Array.isArray(metadata.tags) ? metadata.tags : [],
      estimatedTime: metadata.estimatedTime || undefined,
      content: body
    });
  });
  
  // Generate TypeScript file
  const output = `// Auto-generated by scripts/generate-content-loader.js
// DO NOT EDIT MANUALLY - Changes will be overwritten

export interface CommunityContent {
  slug: string
  title: string
  author: string
  github?: string
  twitter?: string
  linkedin?: string
  topic: string
  difficulty: 'beginner' | 'intermediate' | 'advanced'
  date: string
  tags: string[]
  content: string
  estimatedTime?: string
}

export const communityContributions: CommunityContent[] = ${JSON.stringify(contributions, null, 2)}

export function getCommunityContent(slug: string): CommunityContent | undefined {
  return communityContributions.find(c => c.slug === slug)
}

export function getAllCommunityContent(): CommunityContent[] {
  return communityContributions
}

export function getCommunityContentByTopic(topic: string): CommunityContent[] {
  return communityContributions.filter(c => c.topic === topic)
}
`;
  
  // Write to file
  fs.writeFileSync(OUTPUT_FILE, output, 'utf-8');
  
  console.log(`\n✅ Generated: ${OUTPUT_FILE}`);
  console.log(`📊 Total contributions: ${contributions.length}\n`);
}

// Run
try {
  generateContentLoader();
} catch (error) {
  console.error('❌ Error generating content loader:', error.message);
  process.exit(1);
}
